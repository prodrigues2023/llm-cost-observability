"""Milestone 4, drill 2: retry storm.

The headline scenario docs/diagrams/instrumentation.md describes: a burst
of failures forces retries, and cost per outcome rises far more than
total spend does, because failed attempts are billed but contribute
nothing to the denominator. Enforced by
tests/test_validation_drills.py::test_retry_storm_cost_per_outcome_rises_while_spend_stays_comparatively_flat.
"""

from datetime import datetime, timedelta, timezone

from costkit.store import CostStore
from costkit.traffic import RetryStorm, TrafficConfig, generate_traffic
from eval._shared import make_rates, write_report


def run() -> None:
    store = CostStore(":memory:")
    rates = make_rates()
    now = datetime.now(timezone.utc)
    start = now - timedelta(hours=8)

    storm = RetryStorm(
        feature="checkout-assistant", starts_at=now - timedelta(hours=1), ends_at=now, failure_rate=0.85
    )
    config = TrafficConfig(start=start, end=now, num_tasks=1200, seed=102, retry_storm=storm, base_failure_rate=0.02)
    generate_traffic(store, rates, config)

    baseline = next(
        r for r in store.spend_and_unit_cost_by("feature", since=start, until=now - timedelta(hours=1))
        if r["feature"] == "checkout-assistant"
    )
    recent = next(
        r for r in store.spend_and_unit_cost_by("feature", since=now - timedelta(hours=1))
        if r["feature"] == "checkout-assistant"
    )

    baseline_hourly_spend = baseline["total_spend"] / 7
    recent_hourly_spend = recent["total_spend"] / 1
    spend_ratio = recent_hourly_spend / baseline_hourly_spend
    cost_ratio = recent["cost_per_outcome"] / baseline["cost_per_outcome"]

    verdict = "PASS" if (cost_ratio > 1.3 and cost_ratio > spend_ratio + 0.1) else "FAIL"

    report = f"""# Retry storm drill

**Scenario:** `checkout-assistant`'s failure rate is forced to 85% (from a 2% baseline) for the
last hour of an 8-hour run — every failed attempt still gets retried up to 3 times, per
[outcome-contract.md](../contracts/outcome-contract.md)'s resolution rules.

**Verdict: {verdict}**

## What actually happened

| | Baseline (hourly rate) | Storm hour |
| --- | --- | --- |
| Total spend | ${baseline_hourly_spend:.4f}/h | ${recent_hourly_spend:.4f} |
| Cost per outcome | ${baseline['cost_per_outcome']:.6f} | ${recent['cost_per_outcome']:.6f} |
| Succeeded outcomes | {baseline['succeeded_outcomes']} | {recent['succeeded_outcomes']} |
| Total outcomes attempted | {baseline['total_outcomes']} | {recent['total_outcomes']} |

- **Spend ratio (storm ÷ baseline, per hour): {spend_ratio:.2f}x**
- **Cost-per-outcome ratio: {cost_ratio:.2f}x**

Cost per outcome rose **{cost_ratio - 1:.0%}** while hourly spend only moved **{spend_ratio - 1:.0%}**
— the exact gap [cost-model.md](../cost-model.md) describes: retried attempts are billed (they
show up in spend) but most of the retried tasks still fail outright within their 3-attempt budget
(only {recent['succeeded_outcomes']} of {recent['total_outcomes']} outcomes succeeded), so the
denominator barely grows while the numerator does.

## Why this matters

A dashboard watching total spend alone sees a modest bump, easily lost in normal traffic
variance. Cost per outcome — [ADR-0003](../adr/0003-cost-per-outcome.md)'s headline unit — makes
the same event unambiguous.

---
*Generated by `eval/run_retry_storm_drill.py`. Enforced by
`tests/test_validation_drills.py::test_retry_storm_cost_per_outcome_rises_while_spend_stays_comparatively_flat`,
run on every push.*
"""
    path = write_report("retry-storm-drill.md", report)
    print(f"{verdict}: wrote {path}")
    store.close()


if __name__ == "__main__":
    run()
