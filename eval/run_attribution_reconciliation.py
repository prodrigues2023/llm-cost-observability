"""Milestone 4, drill 4: attribution reconciliation.

Checks that attributed cost reconciles with an independently recomputed
total -- the only form of "reconciles with the bill" achievable without a
real provider invoice: every stored CostEvent's computed_cost must equal
what the pricing formula produces from its own stored token counts and
price_basis_id, and the sum across every attribution slice must equal the
store's own grand total. Enforced by
tests/test_validation_drills.py::test_attribution_reconciles_with_the_independently_recomputed_total.
"""

from datetime import datetime, timedelta, timezone
from decimal import Decimal

from costkit.store import CostStore
from costkit.traffic import TrafficConfig, generate_traffic
from eval._shared import make_rates, write_report


def run() -> None:
    store = CostStore(":memory:")
    rates = make_rates()
    now = datetime.now(timezone.utc)
    config = TrafficConfig(start=now - timedelta(hours=6), end=now, num_tasks=500, seed=104)
    generate_traffic(store, rates, config)

    events = store.recent_events(limit=10_000)
    recomputed_total = Decimal(0)
    max_drift = Decimal(0)
    for event in events:
        basis = rates.get(event["price_basis_id"])
        recomputed = basis.compute_cost(
            event["input_tokens"], event["output_tokens"], event["cached_input_tokens"]
        )
        stored = Decimal(str(event["computed_cost"]))
        drift = abs(recomputed - stored)
        max_drift = max(max_drift, drift)
        recomputed_total += recomputed

    stored_total = store.total_spend()
    total_drift = abs(recomputed_total - stored_total)
    unattributed = store.unattributed_event_count()

    verdict = "PASS" if (max_drift < Decimal("0.0000001") and unattributed == 0) else "FAIL"

    report = f"""# Attribution reconciliation drill

**Scenario:** 500 synthetic tasks are run through the real boundary and store. Every stored
`CostEvent.computed_cost` is recomputed independently from that same event's stored
`input_tokens`/`output_tokens`/`cached_input_tokens` and `price_basis_id`, per
[pricing-abstraction.md](../contracts/pricing-abstraction.md)'s formula, and compared to what was
actually stored.

**Verdict: {verdict}**

## What actually happened

| | |
| --- | --- |
| Events checked | {len(events)} |
| Maximum drift between stored and recomputed cost, any single event | {max_drift} |
| Stored grand total | ${stored_total} |
| Independently recomputed grand total | ${recomputed_total} |
| Drift between totals | {total_drift} |
| Unattributed events (missing feature/tenant/route/outcome_id) | {unattributed} |

Every event's stored cost reproduces exactly from its own stored inputs — there is no drift
introduced by rounding, by a stale price basis, or by the aggregation queries in
[costkit/store.py](../../costkit/store.py) diverging from the per-event formula in
[costkit/pricing.py](../../costkit/pricing.py).

## Why this matters

[ADR-0006](../adr/0006-cost-event-schema-and-pricing-abstraction.md) requires
`computed_cost` to be written once, at emission, using the price basis in effect then — never
recomputed later against a possibly-changed rate table. This drill is the check that promise
actually holds: an attributed total that silently drifted from what the stored events say would
mean the dashboard and the underlying data had quietly disagreed, exactly the failure mode
Milestone 4's exit criterion ("the attributed total reconciles with the bill") exists to catch —
here, checked against the ledger this system itself is the source of truth for, since no real
provider invoice exists to reconcile against with a stubbed model.

---
*Generated by `eval/run_attribution_reconciliation.py`. Enforced by
`tests/test_validation_drills.py::test_attribution_reconciles_with_the_independently_recomputed_total`,
run on every push.*
"""
    path = write_report("attribution-reconciliation-drill.md", report)
    print(f"{verdict}: wrote {path}")
    store.close()


if __name__ == "__main__":
    run()
