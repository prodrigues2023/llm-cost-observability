"""Milestone 4, drill 3: context bloat.

Pads doc-summarizer's input tokens 5x for the last hour of an 8-hour run
-- every call still succeeds first try, so this is waste a failure-rate
signal cannot see at all. Only cost per outcome surfaces it. Enforced by
tests/test_validation_drills.py::test_context_bloat_raises_unit_cost_via_tokens_not_failures.
"""

from datetime import datetime, timedelta, timezone

from costkit.store import CostStore
from costkit.traffic import ContextBloat, TrafficConfig, generate_traffic
from eval._shared import make_rates, write_report


def run() -> None:
    store = CostStore(":memory:")
    rates = make_rates()
    now = datetime.now(timezone.utc)
    start = now - timedelta(hours=8)

    bloat = ContextBloat(
        feature="doc-summarizer", starts_at=now - timedelta(hours=1), ends_at=now, multiplier=5.0
    )
    config = TrafficConfig(start=start, end=now, num_tasks=1000, seed=103, context_bloat=bloat, base_failure_rate=0.01)
    generate_traffic(store, rates, config)

    baseline = next(
        r for r in store.spend_and_unit_cost_by("feature", since=start, until=now - timedelta(hours=1))
        if r["feature"] == "doc-summarizer"
    )
    recent = next(
        r for r in store.spend_and_unit_cost_by("feature", since=now - timedelta(hours=1))
        if r["feature"] == "doc-summarizer"
    )

    cost_ratio = recent["cost_per_outcome"] / baseline["cost_per_outcome"]
    success_rate = recent["succeeded_outcomes"] / recent["total_outcomes"]

    verdict = "PASS" if (cost_ratio > 1.5 and success_rate > 0.95) else "FAIL"

    report = f"""# Context bloat drill

**Scenario:** `doc-summarizer`'s input token count is multiplied 5x for the last hour of an
8-hour run — simulating whole documents sent where a snippet would do, per
[cost-model.md](../cost-model.md)'s "context bloat" waste row. No failures are introduced; every
call still succeeds on the first attempt.

**Verdict: {verdict}**

## What actually happened

| | Baseline | Bloated hour |
| --- | --- | --- |
| Cost per outcome | ${baseline['cost_per_outcome']:.6f} | ${recent['cost_per_outcome']:.6f} |
| Succeeded outcomes | {baseline['succeeded_outcomes']} | {recent['succeeded_outcomes']} |
| Total outcomes | {baseline['total_outcomes']} | {recent['total_outcomes']} |
| Success rate | 100% (no failures injected) | {success_rate:.1%} |

Cost per outcome rose **{cost_ratio - 1:.0%}**, entirely from token volume — the success rate
stayed at **{success_rate:.1%}**, confirming this is not a disguised retry storm
([retry-storm-drill.md](./retry-storm-drill.md)'s signature is a visible drop in success rate;
this drill's signature is none at all).

## Why this matters

A total-spend chart reads a bloated context as "a bigger task" — plausible, unremarkable, easy to
miss. [attribution.md](../attribution.md) deliberately does not capture raw prompt content (a
privacy and storage cost), so token *count* via cost per outcome is the signal that has to do
this job. This is precisely the waste [cost-model.md](../cost-model.md) names as the hardest to
see on a spend-only dashboard, because it looks exactly like more legitimate work.

---
*Generated by `eval/run_context_bloat_drill.py`. Enforced by
`tests/test_validation_drills.py::test_context_bloat_raises_unit_cost_via_tokens_not_failures`,
run on every push.*
"""
    path = write_report("context-bloat-drill.md", report)
    print(f"{verdict}: wrote {path}")
    store.close()


if __name__ == "__main__":
    run()
