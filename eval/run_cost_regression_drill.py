"""Milestone 4, drill 1: cost regression.

Simulates a deploy that quietly swapped support-triage onto a pricier
model tier -- token volume and failure rate unchanged, only the price
basis. Publishes docs/validation/cost-regression-drill.md with the real
numbers. The pass/fail claim itself is enforced by
tests/test_validation_drills.py::test_cost_regression_drill_anomaly_fires,
run on every push; this script re-runs the same scenario and writes up
what happened.
"""

from datetime import datetime, timedelta, timezone

from costkit.budgets import detect_anomalies
from costkit.store import CostStore
from costkit.traffic import FEATURES, ModelDowngrade, TrafficConfig, generate_traffic
from eval._shared import make_rates, write_report


def run() -> None:
    store = CostStore(":memory:")
    rates = make_rates()
    now = datetime.now(timezone.utc)
    start = now - timedelta(hours=8)

    downgrade = ModelDowngrade(
        feature="support-triage", starts_at=now - timedelta(hours=1), ends_at=now, model_tier="large",
    )
    config = TrafficConfig(start=start, end=now, num_tasks=1000, seed=101, model_downgrade=downgrade)
    generate_traffic(store, rates, config)

    baseline = next(
        r for r in store.spend_and_unit_cost_by("feature", since=start, until=now - timedelta(hours=1))
        if r["feature"] == "support-triage"
    )
    recent = next(
        r for r in store.spend_and_unit_cost_by("feature", since=now - timedelta(hours=1))
        if r["feature"] == "support-triage"
    )
    anomalies = detect_anomalies(store, "feature", FEATURES, now, ratio_threshold=1.3)
    flagged = next((a for a in anomalies if a.value == "support-triage"), None)

    verdict = "PASS" if flagged is not None else "FAIL"

    report = f"""# Cost regression drill

**Scenario:** `support-triage` is silently moved from the mixed small/large tier it normally
uses onto `large` exclusively, for the last hour of an 8-hour run — the shape of a deploy that
changed a model choice without anyone noticing the cost consequence. Token volume per call and
the failure rate are both unchanged; only the price basis differs.

**Verdict: {verdict}**

## What actually happened

| | Baseline (hours 1–8 ago) | Last hour (regression) |
| --- | --- | --- |
| Cost per outcome | ${baseline['cost_per_outcome']:.6f} | ${recent['cost_per_outcome']:.6f} |
| Succeeded outcomes | {baseline['succeeded_outcomes']} | {recent['succeeded_outcomes']} |
| Total spend | ${baseline['total_spend']:.4f} | ${recent['total_spend']:.4f} |

Cost per outcome rose **{(recent['cost_per_outcome'] / baseline['cost_per_outcome'] - 1) * 100:.0f}%**.

## Did the anomaly detector catch it?

{"`detect_anomalies` flagged `support-triage` at a **" + f"{flagged.ratio:.2f}x" + "** ratio against its own 6-hour baseline — above the 1.3x threshold this run used." if flagged else "`detect_anomalies` did NOT flag `support-triage` — this is a failed run of the drill, not an expected outcome."}

## Why this matters

A model-tier change is invisible to anything watching total spend per request count — the
request succeeded, at a plausible cost, on an unremarkable code path. It is only visible as a
jump in **cost per outcome for that specific feature**, which is exactly what
[ADR-0005](../adr/0005-budgets-and-alerts.md)'s anomaly detector watches, independent of any
budget threshold.

---
*Generated by `eval/run_cost_regression_drill.py`. Enforced by
`tests/test_validation_drills.py::test_cost_regression_drill_anomaly_fires`, run on every push.*
"""
    path = write_report("cost-regression-drill.md", report)
    print(f"{verdict}: wrote {path}")
    store.close()


if __name__ == "__main__":
    run()
